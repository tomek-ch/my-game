export function registerPixelFont(scene) {
  const chars = Object.keys(GLYPHS).join('');
  const g = scene.make.graphics({}, false);
  [...chars].forEach((ch, i) => {
    const ox = i * CELL_W;
    const lit = [];
    GLYPHS[ch].forEach((row, y) => [...row].forEach((px, x) => px === '#' && lit.push([ox + x, y])));
    g.fillStyle(SHADOW);
    for (const [x, y] of lit) g.fillRect(x + 1, y + 1, 1, 1);
    g.fillStyle(0xffffff);
    for (const [x, y] of lit) g.fillRect(x, y, 1, 1);
  });
  g.generateTexture('pixel-font', chars.length * CELL_W, CELL_H).destroy();

  scene.cache.bitmapFont.add(FONT, Phaser.GameObjects.RetroFont.Parse(scene, {
    image: 'pixel-font',
    width: CELL_W,
    height: CELL_H,
    chars,
    charsPerRow: chars.length,
  }));
}

// Bitmap text in the pixel font at `scale` screen pixels per font pixel, fixed to the screen.
export function pixelText(scene, x, y, text, scale) {
  return scene.add.bitmapText(x, y, FONT, text.toUpperCase()).setScale(scale).setScrollFactor(0);
}
